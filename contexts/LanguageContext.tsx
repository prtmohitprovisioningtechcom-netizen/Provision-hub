const LanguageContext = createContext<LanguageContextType>({
  language: 'en',
  setLanguage: () => {},
  t: (key: string) => key,
});

const STORAGE_KEY = 'bhartiyebazar_lang';

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<Language>('en');

  useEffect(() => {
    try {
      const saved = localStorage.getItem(STORAGE_KEY) as Language;
      if (saved && translations[saved]) {
        setLanguageState(saved);
        if (typeof document !== 'undefined') {
          document.documentElement.lang = saved;
        }
      }
    } catch {
      // ignore
    }
  }, []);

  const setLanguage = (lang: Language) => {
    setLanguageState(lang);
    try {
      localStorage.setItem(STORAGE_KEY, lang);
      if (typeof document !== 'undefined') {
        document.documentElement.lang = lang;
        document.cookie = `bhartiyebazar_lang=${lang}; path=/; max-age=31536000; SameSite=Lax`;
      }
    } catch {
      // ignore
    }
  };

  const t = (key: string): string => {
    const currentDict = translations[language];
    if (currentDict && currentDict[key]) return currentDict[key];
    // Clean fallback: English -> Hindi -> Key itself
    if (translations.en && translations.en[key]) return translations.en[key];
    if (translations.hi && translations.hi[key]) return translations.hi[key];
    return key;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  return useContext(LanguageContext);
}
